_SCHEMA = """\
Ответ — ТОЛЬКО один JSON-объект, без пояснений и без ```-ограждений. Поля:

- "kind": строка, ровно одно из значений:
  - "grammar" — правило или объяснение грамматики (может содержать примеры и небольшие таблицы);
  - "table" — только парадигма/таблица (спряжение, склонение, местоимения) без объяснений;
  - "exercise" — задания, которые нужно выполнить (упражнения, переводы, вставить пропуски);
  - "text" — текст для чтения или диалог;
  - "vocab" — список слов или фраз с переводом;
  - "chat" — приветствия, организационные вопросы, расписание, нет учебного содержания;
  - "other" — нечитаемо или не относится ни к чему из перечисленного.
- "title": короткий заголовок по-русски (до 60 символов), например «Склонение существительных ж.р. на -α».
- "body_md": полное содержимое в Markdown (правила оформления ниже).
- "greek_words": массив объектов {"lemma": строка, "pos": строка, "surface": [строки]}:
  - "lemma" — словарная форма: существительное без артикля в им.п. ед.ч. (μέρα, σπίτι), глагол в 1 л. ед.ч. настоящего времени (γράφω, είμαι), прилагательное в м.р. ед.ч. (καλός);
  - "pos" — одно из "noun", "verb", "adj", "adv", "phrase", "other";
  - "surface" — каждая форма один раз, так, как она встречается в источнике, без артикля и без дефисов, отделяющих окончание (πωλητ-ής → πωλητής);
  - перечисли КАЖДОЕ греческое знаменательное слово, по одному объекту на лемму;
  - НЕ включай артикли, местоимения, союзы, предлоги, частицы и служебные слова (ο, η, το, εγώ, μου, τίποτα, και, αλλά, σε, με, να, δεν, ναι, όχι …);
  - устойчивые выражения можно дать целиком с "pos": "phrase" (например «τι κάνεις;»).
- "topic_hint": короткое и конкретное название темы по-русски, 1–4 слова: если материал про род, окончания или конкретный глагол/предлог — назови их.
  Не пиши общих названий вроде «Склонение существительных» или «Грамматика» — уточняй род и окончания («Склонение м.р. -ης, ж.р. -α, -η»).
  Для упражнений — тема, которую они отрабатывают. Хорошие примеры:
  «Спряжение 1», «Предлог σε», «Склонение ж.р. -α», «Глагол είμαι», «Лексика: дни недели», «Текст: Είμαι φοιτητής».
  Для "vocab" — «Лексика: <тема>», для "text" — «Текст: <заголовок>», для "chat" — пустая строка.
- "confidence": число от 0 до 1. 1.0 — всё разборчиво и ты уверен в каждом символе;
  меньше 0.7 — размыто, обрезано, часть текста не читается или есть сомнения в прочтении.
"""

_RULES = """\
Правила транскрипции:
- Греческий — современная монотоника, буква в букву как в источнике, со всеми ударениями (ά έ ή ί ό ύ ώ ϊ ΐ). Не исправляй, не переводи, не добавляй ударения, которых нет.
- Русский текст — дословно, без пересказа и сокращений.
- Таблицы — Markdown-таблицами с той же структурой строк и столбцов, что в источнике. Подписи над таблицами (заголовки разделов, рамки с окончаниями вроде «-ης, -ες») переноси строкой ### перед таблицей.
- Упражнения — нумерованным списком Markdown: КАЖДЫЙ номер с новой строки, даже если в источнике пункты идут сплошным абзацем. Пропуски, скобки и тире диалога сохраняй как есть. Пример: источник «1. Εγώ ___ (είμαι) φοιτητής. 2. Τι (κάνω, εσύ);» → body_md "1. Εγώ ___ (είμαι) φοιτητής.\n2. Τι (κάνω, εσύ);".
- Переносы слов на конце строки склеивай: «ανοί- / γω» → «ανοίγω».
- Заголовки разделов — через ##. Ничего не выдумывай: нечитаемое место отметь как [неразборчиво].
"""

